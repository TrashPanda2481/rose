// Framebuffer console, v0.1.
//
// Mirrors whatever goes to serial.rs onto the screen too, so a running
// kernel is visible without a serial capture. Additive only: every
// existing `writeln!(com1, ...)` call site keeps working unchanged,
// serial output is untouched, this just gives com1 a second destination
// once the framebuffer is available.
//
// Bring-up ordering matters here. Limine's *own* page tables HHDM-map
// the framebuffer (base revision 3+, see paging.rs), but this kernel
// replaces those tables in paging::init(), and paging.rs's own build()
// now carries that mapping forward (MEMMAP_FRAMEBUFFER added to its
// accepted memmap types). That means `init()` below must not run until
// after paging::init() has returned, and the very first several
// `writeln!`s in kernel_main (before paging is up at all) are
// necessarily serial-only. See main.rs kernel_main for exactly where
// the switchover happens.
//
// State: unlike serial.rs's `Serial`, which is a stateless port-I/O
// handle that's cheap to reconstruct anywhere, a console needs cursor
// position to persist across the many call sites that each construct
// their own writer. That state lives in one global behind the same
// hand-rolled SpinLock used elsewhere (see mem.rs), not a fresh local.
//
// Color: v1 is plain white-on-black, no branding. That's also the most
// portable choice available: white packs to all-ones in whatever bits
// the red/green/blue masks occupy, black packs to all-zero, so getting
// this wrong from a mask/shift mistake isn't really possible the way a
// specific hex color would be. Anything past monochrome is deferred.
//
// Scrolling: a raw byte-level memmove of the framebuffer up by one text
// row (8 scanlines), then a zero-fill of the vacated row. The zero-fill
// is only correct because the background color is black (0x000000) in
// every pixel format Limine reports (whole-byte-zero regardless of
// channel order/width) -- if the background ever becomes a non-black
// color, this fast path has to change to a per-pixel bg fill instead of
// a memset.
//
// Not handled in v1: Unicode (only ASCII 0x20-0x7E draws; anything else
// prints as '?'), double-buffering (each character draws straight to
// the framebuffer, acceptable at this output rate), and any call site
// that runs from interrupt/exception context before or independent of
// the rest of the kernel being in a known-good state -- the panic
// handler, the heap alloc-error handler, and the unhandled-CPU-exception
// path in idt.rs all stay serial-only on purpose, same reasoning as the
// existing panic handler: they have to work even if the console itself
// is what's broken. timer.rs's first-tick log also stays serial-only,
// since it fires from the IRQ0 handler and this console's lock is not
// IRQ-safe (nothing here disables interrupts while held).

