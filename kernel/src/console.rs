const GLYPH_SIZE: u64 = 8;

/// Everything drawing a glyph needs: base address (virtual, HHDM-derived,
/// valid once paging.rs has carried the framebuffer's mapping forward),
/// scanline geometry, and the two packed pixel values in use. Computed
/// once in `init()` from the Limine `Framebuffer` response and never
/// touched again; the response struct itself doesn't need to stick
/// around past that.
struct Geometry {
    addr: u64,
    pitch: u64,
    bytes_per_pixel: u64,
    fg: u32,
    bg: u32,
}

struct Cursor {
    col: u32,
    row: u32,
    cols: u32,
    rows: u32,
}

struct ConsoleState {
    geo: Geometry,
    cursor: Cursor,
}

/// `None` until `init()` runs. Every write before that (or on a system
/// with no framebuffer at all) is a silent no-op, not a panic -- see
/// `Console::write_str`.
static CONSOLE: SpinLock<Option<ConsoleState>> = SpinLock::new(None);

/// Packs an 8-bit-per-channel color into this framebuffer's native pixel
/// format using the red/green/blue mask size/shift fields Limine
/// reports, instead of assuming a specific bit layout (RGB vs BGR,
/// 24 vs 32bpp). White and black both survive any mask/shift mistake
/// unscathed (all-ones or all-zero regardless of where the bits land),
/// which is part of why v1 only uses those two colors.
fn pack_color(fb: &limine::framebuffer::Framebuffer, r: u8, g: u8, b: u8) -> u32 {
    let rv = ((r as u32) >> (8 - fb.red_mask_size)) << fb.red_mask_shift;
    let gv = ((g as u32) >> (8 - fb.green_mask_size)) << fb.green_mask_shift;
    let bv = ((b as u32) >> (8 - fb.blue_mask_size)) << fb.blue_mask_shift;
    rv | gv | bv
}

/// Sets up the global console state from a Limine framebuffer response.
/// Must not run until after `paging::init()` has returned (see module
/// doc comment); everything here writes through `fb.address()`, which
/// is only backed by a valid mapping in the kernel's own page tables
/// from that point on.
///
/// Safety: caller must guarantee paging::init() has already run and
/// that `fb` came from a still-valid Limine response (true for the one
/// call site in kernel_main).
pub unsafe fn init(fb: &limine::framebuffer::Framebuffer) {
    if fb.bpp % 8 != 0 || fb.bpp == 0 {
        // No format this module knows how to pack a color into (e.g. a
        // sub-byte-per-pixel mode); leave CONSOLE as None so writes stay
        // silent no-ops rather than corrupting memory with a wrong
        // stride assumption.
        return;
    }
    let bytes_per_pixel = (fb.bpp / 8) as u64;
    let fg = pack_color(fb, 0xFF, 0xFF, 0xFF);
    let bg = pack_color(fb, 0x00, 0x00, 0x00);
    let geo = Geometry {
        addr: fb.address() as u64,
        pitch: fb.pitch,
        bytes_per_pixel,
        fg,
        bg,
    };
    let cols = (fb.width / GLYPH_SIZE) as u32;
    let rows = (fb.height / GLYPH_SIZE) as u32;

    // Clear to background before anything gets drawn, so leftover
    // firmware/bootloader framebuffer contents don't show through
    // between glyphs.
    unsafe {
        core::ptr::write_bytes(geo.addr as *mut u8, 0, (fb.height * fb.pitch) as usize);
    }

    *CONSOLE.lock() = Some(ConsoleState {
        geo,
        cursor: Cursor {
            col: 0,
            row: 0,
            cols,
            rows,
        },
    });
}

/// Writes one packed pixel value at (x, y). No bounds check against
/// width: every call site already derives x from `cursor.col * 8`,
/// which `put_char`'s wrap-at-`cols` logic keeps inside the framebuffer;
/// y is bounds-checked by the scroll-before-overflow logic in
/// `put_char` instead of here.
fn draw_pixel(geo: &Geometry, x: u64, y: u64, color: u32) {
    let offset = (y * geo.pitch + x * geo.bytes_per_pixel) as usize;
    unsafe {
        let ptr = (geo.addr as *mut u8).add(offset);
        match geo.bytes_per_pixel {
            4 => core::ptr::write_volatile(ptr as *mut u32, color),
            2 => core::ptr::write_volatile(ptr as *mut u16, color as u16),
            3 => {
                core::ptr::write_volatile(ptr, (color & 0xFF) as u8);
                core::ptr::write_volatile(ptr.add(1), ((color >> 8) & 0xFF) as u8);
                core::ptr::write_volatile(ptr.add(2), ((color >> 16) & 0xFF) as u8);
            }
            1 => core::ptr::write_volatile(ptr, color as u8),
            _ => {} // unreachable given the bpp % 8 == 0 check in init()
        }
    }
}

fn draw_glyph(geo: &Geometry, col: u32, row: u32, byte: u8) {
    let glyph_index = if (0x20..=0x7E).contains(&byte) {
        byte
    } else {
        b'?'
    };
    let glyph = &FONT8X8[glyph_index as usize];
    let x0 = col as u64 * GLYPH_SIZE;
    let y0 = row as u64 * GLYPH_SIZE;
    for (ry, bits) in glyph.iter().enumerate() {
        for rx in 0..GLYPH_SIZE {
            let on = bits & (1 << rx) != 0;
            let color = if on { geo.fg } else { geo.bg };
            draw_pixel(geo, x0 + rx, y0 + ry as u64, color);
        }
    }
}

/// Scrolls the framebuffer up by one text row (`GLYPH_SIZE` scanlines)
/// and clears the vacated row. See module doc comment: the clear is a
/// raw zero-fill, which is only correct while the background color is
/// black.
fn scroll(state: &mut ConsoleState) {
    let row_bytes = (GLYPH_SIZE * state.geo.pitch) as usize;
    let total_bytes = (state.cursor.rows as u64 * GLYPH_SIZE * state.geo.pitch) as usize;
    unsafe {
        let base = state.geo.addr as *mut u8;
        core::ptr::copy(base.add(row_bytes), base, total_bytes - row_bytes);
        core::ptr::write_bytes(base.add(total_bytes - row_bytes), 0, row_bytes);
    }
    state.cursor.row -= 1;
}

fn put_char(state: &mut ConsoleState, byte: u8) {
    match byte {
        b'\n' => {
            state.cursor.col = 0;
            state.cursor.row += 1;
        }
        b'\r' => {
            state.cursor.col = 0;
        }
        0x00..=0x1F | 0x7F => {
            // Other control bytes: no glyph, no cursor movement. Not
            // expected from any current writeln! call site (all ASCII
            // literals/formatted numbers/hex), but a stray one shouldn't
            // corrupt the grid with a phantom blank cell.
        }
        _ => {
            draw_glyph(&state.geo, state.cursor.col, state.cursor.row, byte);
            state.cursor.col += 1;
            if state.cursor.col >= state.cursor.cols {
                state.cursor.col = 0;
                state.cursor.row += 1;
            }
        }
    }
    if state.cursor.row >= state.cursor.rows {
        scroll(state);
    }
}

/// Framebuffer console writer. Zero-sized, mirroring `serial::Serial`'s
/// shape; all real state lives in the `CONSOLE` global behind its
/// SpinLock, not in this handle.
pub struct Console;

impl Console {
    fn write_str(&mut self, s: &str) {
        let mut guard = CONSOLE.lock();
        if let Some(state) = guard.as_mut() {
            for &b in s.as_bytes() {
                put_char(state, b);
            }
        }
        // Console not yet initialized (or no framebuffer at all):
        // silent no-op, matching the doc comment on CONSOLE above.
    }
}

impl core::fmt::Write for Console {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        Console::write_str(self, s);
        Ok(())
    }
}

/// Writes to both serial and the framebuffer console from one handle,
/// so every existing `writeln!(com1, ...)` call site keeps its call
/// shape; only the type of `com1` changes at the one shadow-rebind
/// point in kernel_main (see main.rs), not any of the ~70 call bodies.
pub struct Dual {
    serial: crate::serial::Serial,
    console: Console,
}

impl Dual {
    /// Upgrades an existing `Serial` handle into a `Dual` writer.
    /// `Serial` is stateless port I/O, so this doesn't lose or
    /// duplicate any hardware state; output just starts mirroring to
    /// the screen (once `init()` above has run) from this point
    /// forward. This is the path kernel_main uses right after
    /// `paging::init()`, so the boot-ok/memmap/hhdm-offset lines that
    /// precede it stay serial-only.
    pub fn upgrade(serial: crate::serial::Serial) -> Self {
        Dual {
            serial,
            console: Console,
        }
    }

    /// Fresh `Dual` writer for call sites with no existing `Serial`
    /// handle to upgrade, mirroring `Serial::init()`'s own
    /// cheap-to-reconstruct-anywhere pattern. Every one of these call
    /// sites runs well after boot (usermode syscall hooks), so the
    /// console is already initialized by the time this is called.
    pub fn init() -> Self {
        Dual {
            serial: crate::serial::Serial::init(),
            console: Console,
        }
    }
}

impl core::fmt::Write for Dual {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        self.serial.write_str(s);
        Console::write_str(&mut self.console, s);
        Ok(())
    }
}
